#!/usr/bin/env python3
"""Generate docs/reference/config.md from config-struct doc comments
— the structs across core + impl crates are the source of truth."""
import os, pathlib, re, sys

# Sources live in the main checkout — normally docs/ is a worktree of it
# (so `..` works); under bupha the docs sha runs detached, so TAMIAS_ROOT
# points at the real repo.
ROOT = pathlib.Path(
    os.environ.get("TAMIAS_ROOT") or pathlib.Path(__file__).parent / "..")
OUT  = pathlib.Path(__file__).parent / "reference" / "config.md"

# file → {struct: section title}; order preserved
SRCS = {
    "crates/tamias-core/src/config.rs": {
        "Config": "Top level",
        "VaultConfig": "`[vaults.NAME]` — a named vault backend",
        "EnvRouteTable": "`[envs]` — env → vault routing (table form)",
        "DeployConfig": "`[deploy.NAME]` — a write-only push target",
        "Guardrails": "`[guardrails]` — advisory op table",
        "ServeConfig": "`[serve]` — the `tamias serve` surface",
        "PdpConfig": "`[serve.pdp]` — the external policy decision point",
    },
}
SRC = {n: (ROOT / f).read_text()
       for f, names in SRCS.items() for n in names}
TITLES = {n: t for names in SRCS.values() for n, t in names.items()}
STRUCTS = [n for names in SRCS.values() for n in names]

SIMPLE = {"String": "string", "PathBuf": "path", "bool": "bool",
          "u16": "int", "u64": "int", "usize": "int",
          "Vec<String>": "list",
          "Vec<Op>": "op list",
          "BTreeMap<String, VaultConfig>": "{name: vault}",
          "BTreeMap<Env, EnvRoute>": "{env: vault|{vault}}",
          "BTreeMap<String, Ref>": "{VAR: tamias://ref}",
          "BTreeMap<String, DeployConfig>": "{name: target}",
          "Guardrails": "table",
          "GuardDefault": '"allow"|"deny"',
          "ServeConfig": "table",
          "PdpConfig": "table"}

def fields(name):
    m = re.search(rf"pub struct {name} \{{(.*?)\n\}}", SRC[name], re.S)
    if not m: return []
    rows = []
    for fm in re.finditer(
            r"((?:\s*(?:///|#\[)[^\n]*\n)+)\s*"
            r"pub (\w+): ([^\n]+)", m.group(1)):
        prelude = fm.group(1)
        doc = " ".join(l.split("///", 1)[1].strip()
                       for l in prelude.splitlines() if "///" in l)
        fname, ty = fm.group(2), fm.group(3).strip().rstrip(",")
        opt = (ty.startswith("Option")
               or "serde(default" in prelude)
        inner = ty[7:-1] if ty.startswith("Option") else ty
        rows.append((fname, SIMPLE.get(inner, inner),
                     "" if opt else "required", doc or "—"))
    return rows

out = ["# Config — `tamias.toml`",
       "<!-- generated by gen-config-docs.py — edit the struct doc comments,",
       "     not this file -->", ""]
for name in STRUCTS:
    out += [f"## {TITLES[name]}", "",
            "| field | type | required | notes |",
            "|---|---|---|---|"]
    for fname, ty, req, doc in fields(name):
        doc = (doc.replace("|", "\\|")
                  .replace("<", "&lt;").replace(">", "&gt;"))
        out.append(
            f"| `{fname}` | `{ty}` | {req or 'optional'} | {doc} |")
    out.append("")
out += [
    "## `[envs]` route forms", "",
    "Either a bare vault name or the table above:", "",
    "```toml", "[envs]", 'dev = "local"', 'prod = { vault = "cloud" }',
    "```", "",
    "## Constraints", "",
    "- `deny_unknown_fields`: typos in field names fail the load.",
    "- Search order: `--config` → `$TAMIAS_CONFIG` → `./tamias.toml` →",
    "  `~/.config/tamias/tamias.toml`. The file is optional — no",
    "  `tamias.toml` anywhere just means defaults (local age vault,",
    "  `dev` env).",
    "- Token values never live in the file — `token_env` fields name",
    "  the env var that carries them.",
    "- `tamias schema` emits the JSON Schema for this shape;",
    "  `tamias check` validates a real file end-to-end.",
    ""]
OUT.write_text("\n".join(out))
print(f"wrote {OUT}")
